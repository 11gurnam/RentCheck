import { test, expect } from "@playwright/test";
import { createClient } from "@supabase/supabase-js";
import AxeBuilder from "@axe-core/playwright";
import { localBackendConfiguration } from "../helpers/local-backend";
import { fixtureAdmin } from "../helpers/admin-fixture";

test("admin dashboard, listing suspension, private notes and responsive navigation", async ({ page }, info) => {
  test.setTimeout(120000);
  const config = localBackendConfiguration();
  if (!config) throw new Error("Local backend required");
  const service = createClient(config.url, config.serviceKey, { auth: { persistSession: false } });
  const email = `admin-dashboard-${crypto.randomUUID()}@example.test`;
  const password = "Synthetic dashboard browser password";
  const account = await service.auth.admin.createUser({ email, password, email_confirm: true });
  expect(account.error).toBeNull();
  const user = account.data.user!.id;
  let property: string | undefined;
  try {
    fixtureAdmin(user, true);
    const client = createClient(config.url, config.publicKey, { auth: { persistSession: false } });
    await client.auth.signInWithPassword({ email, password });
    const name = `Dashboard browser ${crypto.randomUUID().slice(0, 8)}`;
    const created = await client.rpc("create_property", { p_input: { name, address: `Synthetic dashboard lane ${name}`, state: "Delhi", city: "Browser city", locality: "Test area", type: "Flat", min: 1000, max: 2000, synthetic: true }, p_acknowledged: true });
    expect(created.error).toBeNull(); property = created.data;
    await page.goto("/sign-in");
    await page.getByLabel("Email address").fill(email);
    await page.getByLabel("Password", { exact: true }).fill(password);
    await page.getByRole("button", { name: "Sign in", exact: true }).click();
    await expect(page).toHaveURL(/\/account$/);
    const mainNavigation = page.getByRole("navigation", { name: "Main navigation" });
    await expect(mainNavigation.getByRole("link")).toHaveText(["Explore", "Add a place", "Admin Dashboard"]);
    await expect(page.getByRole("heading", { name: "Your admin workspace" })).toBeVisible();
    await expect(page.getByRole("link", { name: "Saved places", exact: true })).toHaveCount(0);
    await page.goto("/admin");
    await expect(page.getByRole("heading", { name: "Platform overview" })).toBeVisible();
    const navigation = page.getByRole("navigation", { name: "Admin navigation" });
    await expect(navigation.getByRole("link")).toHaveCount(9);
    expect((await new AxeBuilder({ page }).withTags(["wcag2a", "wcag2aa", "wcag21aa"]).analyze()).violations).toEqual([]);
    await page.screenshot({ path: info.outputPath("admin-overview.png"), fullPage: true });
    await navigation.getByRole("link", { name: "Properties", exact: true }).click();
    await page.getByLabel("Search", { exact: true }).fill(name);
    await expect(page.getByRole("dialog", { name: "Filter properties" })).not.toBeVisible();
    await page.getByRole("button", { name: "Filters", exact: true }).click();
    const filters = page.getByRole("dialog", { name: "Filter properties" });
    await filters.getByRole("combobox", { name: "Status", exact: true }).selectOption("published");
    await filters.getByRole("button", { name: "Apply filters", exact: true }).click();
    await expect(page.getByLabel("Search", { exact: true })).toHaveValue(name);
    await expect(page.locator(".admin-active-filters")).toContainText("1 filter applied");
    await page.getByRole("button", { name: "Search", exact: true }).click();
    await expect(page.getByRole("status")).toContainText("1 matching properties");
    await page.locator(".admin-active-filters").getByRole("link", { name: "Clear filters" }).click();
    await expect(page).toHaveURL(url => !url.searchParams.has("status"));
    await expect(page.getByLabel("Search", { exact: true })).toHaveValue(name);
    await page.getByRole("button", { name: "Manage record", exact: true }).click();
    const manage = page.getByRole("dialog", { name: "Manage record", exact: true });
    await manage.getByRole("combobox", { name: "Action", exact: true }).selectOption("hidden");
    await manage.getByLabel("Reason", { exact: true }).fill("Synthetic suspicious listing investigation.");
    await manage.getByRole("button", { name: "Review action", exact: true }).click();
    const confirm = page.getByRole("dialog", { name: "Confirm administrative action", exact: true });
    await confirm.getByRole("button", { name: "Confirm and save" }).click();
    await expect(confirm.getByRole("status")).toContainText("Action saved and audited");
    await page.keyboard.press("Escape"); await page.keyboard.press("Escape");
    await expect(page.locator("tbody")).toContainText("hidden");
    await page.getByRole("link", { name: "Inspect record", exact: true }).click();
    await page.getByRole("button", { name: "Add private note", exact: true }).click();
    const notes = page.getByRole("dialog", { name: "Add private note", exact: true });
    await notes.getByLabel("Private internal note", { exact: true }).fill("Synthetic private administrative note.");
    await notes.getByRole("button", { name: "Review action", exact: true }).click();
    await confirm.getByRole("button", { name: "Confirm and save" }).click();
    await expect(confirm.getByRole("status")).toContainText("Private note saved");
    await page.keyboard.press("Escape"); await page.keyboard.press("Escape");
    await expect(page.locator(".admin-notes")).toContainText("Synthetic private administrative note.");
    await page.goto("/admin/users"); await expect(page.getByRole("heading", { name: "Users", exact: true })).toBeVisible();
    await page.goto("/admin/disputes"); await expect(page.getByRole("heading", { name: "Disputes & Reports", exact: true })).toBeVisible();
    await page.goto("/admin/audit"); await expect(page.getByRole("heading", { name: /Audit/i })).toBeVisible();
    await page.goto("/admin"); await page.setViewportSize({ width: 390, height: 844 });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    expect((await new AxeBuilder({ page }).withTags(["wcag2a", "wcag2aa", "wcag21aa"]).analyze()).violations).toEqual([]);
    await page.screenshot({ path: info.outputPath("admin-mobile.png"), fullPage: true });
  } finally {
    await service.auth.admin.deleteUser(user);
    if (property) await service.from("properties").delete().eq("id", property);
  }
});
